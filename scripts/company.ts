/**
 * The company package, rendered into every role.
 *
 * `company/default/` is the one place Northwind Facilities is described: `company.json` for the facts
 * a program needs, and three markdown documents written for an agent to read. Every role in
 * `agents/` needs those facts, and a published role has to be self-contained — it cannot read a
 * directory outside its own package — so the facts reach a role as generated copies inside it:
 *
 *   skills/company-handbook/SKILL.md                    the handbook, and the entry point
 *   skills/company-handbook/references/pricing.md       what things cost
 *   skills/company-handbook/references/policies.md       the rules and who decides
 *   skills/company-handbook/references/facts.json       the same facts, for the role's own code
 *
 * One writer, many readers. `npm run sync-company` writes the copies; `sync-company.test.ts`
 * regenerates them in memory and fails when a copy has drifted, so a hand-edited copy cannot survive
 * a test run. The numbers are checked while rendering, not trusted: a price in `pricing.md` that
 * `company.json` does not record, or an escalation to a person who does not work here, is an error
 * rather than a document.
 *
 * This module is pure apart from `readSource` and `syncCompany`, so a test can render the whole
 * catalogue into memory and compare bytes without touching the tree.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** Where the company is described, relative to the repository root. */
export const COMPANY_DIRECTORY = "company/default";

/** The skill name every role gets: the folder, and the `name` in its frontmatter. */
export const HANDBOOK_SKILL = "company-handbook";

/**
 * The departments a person can work in. Roles find people by department (Purchasing's lead is the
 * person in `purchasing`), so a misspelt one would leave a role naming nobody.
 */
export const DEPARTMENTS: readonly string[] = ["office", "maintenance", "purchasing", "field"];

/** The program that writes the copies; named in every generated file's header. */
export const GENERATOR = "scripts/sync-company.ts";

/** The company as it is written down: one JSON record and the three documents beside it. */
export interface CompanySource {
  readonly company: Readonly<Record<string, unknown>>;
  readonly handbook: string;
  readonly policies: string;
  readonly pricing: string;
}

/** A generated file: its path from the repository root, and its exact bytes. */
export interface GeneratedFile {
  readonly path: string;
  readonly content: string;
}

const HEADER = (file: string): string =>
  `<!-- Generated from ${COMPANY_DIRECTORY}/${file} by ${GENERATOR}. ` +
  "Do not edit this file: run `npm run sync-company` from the repository root and commit the result. -->";

/** Reads the company package. Throws with the path when a file is missing or is not JSON. */
export function readSource(root: string): CompanySource {
  const at = (file: string): string => join(root, COMPANY_DIRECTORY, file);
  const read = (file: string): string => readFileSync(at(file), "utf8");
  let company: unknown;
  try {
    company = JSON.parse(read("company.json")) as unknown;
  } catch (error) {
    throw new Error(`${at("company.json")} could not be read: ${String(error)}`);
  }
  const record = asRecord(company);
  if (record === undefined) throw new Error(`${at("company.json")} must hold a JSON object.`);
  return {
    company: record,
    handbook: read("handbook.md"),
    policies: read("policies.md"),
    pricing: read("pricing.md"),
  };
}

/**
 * Everything wrong with the company package, each issue naming the file and the place in it: the
 * numbers in the prose against the numbers in the record, the people an escalation points at, the
 * headcount against the field structure, and the identifiers that must be unique.
 *
 * Rendered copies are checked against the same record, so a document cannot quietly disagree with
 * the facts the tools quote.
 */
export function companyIssues(source: CompanySource): readonly string[] {
  const issues: string[] = [];
  const add = (where: string, message: string): void => {
    issues.push(`company/default/${where}: ${message}`);
  };
  const { company } = source;

  const profile = asRecord(company.profile);
  if (profile === undefined) add("company.json", "profile is missing");
  const field = asRecord(profile?.field);
  if (field === undefined) {
    add("company.json", "profile.field is missing");
  } else {
    const headcount = profile?.headcount;
    const total =
      number(field, "cleaningCrews") * number(field, "cleanersPerCrew") +
      number(field, "maintenanceTechnicians") +
      number(field, "office");
    if (!Number.isSafeInteger(headcount) || headcount !== total) {
      add(
        "company.json",
        `profile.headcount is ${String(headcount)} but the field structure adds up to ${total}`,
      );
    }
  }

  const people = asArray(company.people);
  if (people === undefined) add("company.json", "people is missing");
  const personIds = new Set<string>();
  // An alias names one person: roles route a complaint away from whoever it names.
  const aliases = new Map<string, string>();
  for (const [index, entry] of (people ?? []).entries()) {
    const person = asRecord(entry);
    const id = person === undefined ? undefined : text(person.id);
    if (id === undefined) {
      add("company.json", `people[${index}] has no id`);
      continue;
    }
    if (personIds.has(id)) add("company.json", `people[${index}] repeats the id ${id}`);
    personIds.add(id);
    if (text(asRecord(person)?.email) === undefined) {
      add("company.json", `people[${index}] (${id}) has no email`);
    }
    const named = asRecord(person)?.aliases;
    if (named !== undefined) {
      const list = asArray(named);
      if (list === undefined) {
        add("company.json", `people[${index}] (${id}) aliases must be a list of names`);
      }
      for (const [at, alias] of (list ?? []).entries()) {
        if (typeof alias !== "string" || alias.trim() === "") {
          add("company.json", `people[${index}] (${id}) aliases[${at}] must be a non-empty string`);
          continue;
        }
        const key = alias.trim().toLowerCase();
        const holder = aliases.get(key);
        if (holder !== undefined) {
          add(
            "company.json",
            `people[${index}] (${id}) repeats the alias ${JSON.stringify(alias)}, already ${holder}'s`,
          );
        }
        aliases.set(key, holder ?? id);
      }
    }
    const department = asRecord(person)?.department;
    if (typeof department !== "string" || !DEPARTMENTS.includes(department)) {
      add(
        "company.json",
        `people[${index}] (${id}) has the department ${JSON.stringify(department)}; use one of ${DEPARTMENTS.join(", ")}`,
      );
    }
  }

  const priceBook = asArray(company.priceBook);
  if (priceBook === undefined) add("company.json", "priceBook is missing");
  const priceIds = new Set<string>();
  const amounts = new Map<number, string>();
  for (const [index, entry] of (priceBook ?? []).entries()) {
    const item = asRecord(entry);
    if (item === undefined) {
      add("company.json", `priceBook[${index}] is not an object`);
      continue;
    }
    const id = text(item.id);
    if (id === undefined) {
      add("company.json", `priceBook[${index}] has no id`);
      continue;
    }
    if (priceIds.has(id)) add("company.json", `priceBook[${index}] repeats the id ${id}`);
    priceIds.add(id);
    const price = item.unitPriceCents;
    if (!Number.isSafeInteger(price) || (price as number) < 0) {
      add("company.json", `priceBook[${index}] (${id}) needs a whole, non-negative unitPriceCents`);
    }
    const minimum = item.minimumCents;
    if (minimum !== null && (!Number.isSafeInteger(minimum) || (minimum as number) <= 0)) {
      add(
        "company.json",
        `priceBook[${index}] (${id}) has a minimumCents that is not a positive whole number of cents, or null`,
      );
    }
  }
  // Every figure the company records as money, by the value in cents: the rule the prose is held to.
  walkCents(company, "", amounts);

  for (const [index, entry] of (asArray(company.services) ?? []).entries()) {
    const service = asRecord(entry);
    if (service === undefined) continue;
    for (const [at, id] of (asArray(service.priceBookIds) ?? []).entries()) {
      if (typeof id !== "string" || !priceIds.has(id)) {
        add(
          "company.json",
          `services[${index}].priceBookIds[${at}] names ${String(id)}, which is not a price book item`,
        );
      }
    }
  }

  for (const [index, entry] of (asArray(company.escalation) ?? []).entries()) {
    const rule = asRecord(entry);
    const person = rule === undefined ? undefined : text(rule.toPersonId);
    if (person === undefined) {
      add("company.json", `escalation[${index}] names no one`);
    } else if (!personIds.has(person)) {
      add("company.json", `escalation[${index}] goes to ${person}, who is not one of the people`);
    }
  }

  // A ticket type no role accepts goes to the person named here (the office extension's person routes,
  // RASF-3490). A route to nobody, or two routes for one type, would leave the hand-off ambiguous.
  const routes = company.ticketRoutes;
  if (routes !== undefined && asArray(routes) === undefined) {
    add("company.json", "ticketRoutes must be a list");
  }
  const routedTypes = new Set<string>();
  for (const [index, entry] of (asArray(routes) ?? []).entries()) {
    const route = asRecord(entry);
    const type = route === undefined ? undefined : text(route.type);
    if (type === undefined || !ROUTE_TYPE.test(type)) {
      add(
        "company.json",
        `ticketRoutes[${index}] has the type ${JSON.stringify(type ?? route?.type)}, which is not a ticket type like finance.review`,
      );
    } else if (routedTypes.has(type)) {
      add("company.json", `ticketRoutes[${index}] repeats the type ${type}; route each type once`);
    } else {
      routedTypes.add(type);
    }
    const person = route === undefined ? undefined : text(route.toPersonId);
    if (person === undefined) add("company.json", `ticketRoutes[${index}] names no one`);
    else if (!personIds.has(person)) {
      add("company.json", `ticketRoutes[${index}] goes to ${person}, who is not one of the people`);
    }
  }

  // The policy record names its deciders by id too: a policy that points at nobody is a dead end.
  const policies = asRecord(company.policies);
  for (const [section, value] of Object.entries(policies ?? {})) {
    const policy = asRecord(value);
    if (policy === undefined) continue;
    for (const key of [
      "approver",
      "ownerApprover",
      "creditNeeds",
      "refundNeeds",
      "complaintOwner",
    ]) {
      const id = text(policy[key]);
      if (id !== undefined && !personIds.has(id)) {
        add("company.json", `policies.${section}.${key} names ${id}, who is not one of the people`);
      }
    }
  }

  departmentIssues(source, personIds, add);

  for (const [file, body] of [
    ["pricing.md", source.pricing],
    ["policies.md", source.policies],
  ] as const) {
    for (const amount of moneyAmounts(body)) {
      if (!amounts.has(amount.cents)) {
        add(
          file,
          `states ${amount.text}, which company.json does not record in cents; add the figure to company.json, or correct the prose`,
        );
      }
    }
  }
  // The other direction: a price the book records but the prose never states is an incomplete price
  // list, which is worse than a wrong one because nobody can see it is missing.
  const stated = new Set(moneyAmounts(source.pricing).map((amount) => amount.cents));
  for (const [index, entry] of (priceBook ?? []).entries()) {
    const item = asRecord(entry);
    if (item === undefined) continue;
    const id = text(item.id) ?? `priceBook[${index}]`;
    for (const key of ["unitPriceCents", "minimumCents"] as const) {
      const cents = item[key];
      if (typeof cents === "number" && Number.isSafeInteger(cents) && !stated.has(cents)) {
        add(
          "pricing.md",
          `does not state ${cents} cents (${key} of ${id}); the price list must show every price and minimum`,
        );
      }
    }
  }

  return issues;
}

/** A routed ticket type: lowercase words joined by dots, at least one dot. */
const ROUTE_TYPE = /^[a-z]+(\.[a-z-]+)+$/;

/** The sentences policies.md uses for each value of staffPolicies.overtimeNeedsApproval. */
const OVERTIME_NEEDS_APPROVAL = "Overtime needs a person's approval before it is worked.";
const OVERTIME_NEEDS_NO_APPROVAL =
  "Overtime does not need a person's approval before it is worked.";

/**
 * The sections the departmental agents read: suppliers and the supply catalog, crews, staff policies,
 * the approved marketing claims and the purchase-order limit. Each is held to the same promises as
 * the rest: ids are unique, every reference is to something that exists, every crew lead and contact
 * is a person, the crews account for the headcount, and the prose says what the record says.
 */
function departmentIssues(
  source: CompanySource,
  personIds: ReadonlySet<string>,
  add: (where: string, message: string) => void,
): void {
  const { company } = source;
  const unique = (section: string, entries: readonly unknown[] | undefined): Set<string> => {
    const ids = new Set<string>();
    if (entries === undefined) {
      add("company.json", `${section} is missing`);
      return ids;
    }
    for (const [index, entry] of entries.entries()) {
      const id = text(asRecord(entry)?.id);
      if (id === undefined) add("company.json", `${section}[${index}] has no id`);
      else if (ids.has(id)) add("company.json", `${section}[${index}] repeats the id ${id}`);
      else ids.add(id);
    }
    return ids;
  };
  const whole = (value: unknown, minimum: number): boolean =>
    typeof value === "number" && Number.isSafeInteger(value) && value >= minimum;

  const suppliers = asArray(company.suppliers);
  const supplierIds = unique("suppliers", suppliers);
  for (const [index, entry] of (suppliers ?? []).entries()) {
    const supplier = asRecord(entry);
    if (supplier === undefined) continue;
    const id = text(supplier.id) ?? `suppliers[${index}]`;
    if (typeof supplier.approved !== "boolean") {
      add("company.json", `suppliers[${index}] (${id}) needs approved to be true or false`);
    }
    if (!whole(supplier.leadTimeDays, 1)) {
      add("company.json", `suppliers[${index}] (${id}) needs a whole leadTimeDays of at least 1`);
    }
    if (text(supplier.name) === undefined || text(supplier.contactEmail) === undefined) {
      add("company.json", `suppliers[${index}] (${id}) needs a name and a contactEmail`);
    }
    const name = text(supplier.name);
    if (name !== undefined && !source.handbook.includes(name)) {
      add(
        "handbook.md",
        `does not name the supplier ${name}; the handbook must say who we buy from`,
      );
    }
  }

  const catalog = asArray(company.supplyCatalog);
  unique("supplyCatalog", catalog);
  for (const [index, entry] of (catalog ?? []).entries()) {
    const item = asRecord(entry);
    if (item === undefined) continue;
    const id = text(item.id) ?? `supplyCatalog[${index}]`;
    const supplier = text(item.supplierId);
    if (supplier === undefined || !supplierIds.has(supplier)) {
      add(
        "company.json",
        `supplyCatalog[${index}] (${id}) names the supplier ${String(item.supplierId)}, who is not one of the suppliers`,
      );
    }
    if (!whole(item.unitCostCents, 1)) {
      add("company.json", `supplyCatalog[${index}] (${id}) needs a whole, positive unitCostCents`);
    }
    for (const key of ["reorderPoint", "reorderQuantity"] as const) {
      if (!whole(item[key], key === "reorderQuantity" ? 1 : 0)) {
        add("company.json", `supplyCatalog[${index}] (${id}) needs a whole ${key}`);
      }
    }
    if (text(item.name) === undefined || text(item.unit) === undefined) {
      add("company.json", `supplyCatalog[${index}] (${id}) needs a name and a unit`);
    }
  }

  const crews = asArray(company.crews);
  unique("crews", crews);
  let crewMembers = 0;
  for (const [index, entry] of (crews ?? []).entries()) {
    const crew = asRecord(entry);
    if (crew === undefined) continue;
    const id = text(crew.id) ?? `crews[${index}]`;
    const lead = crew.leadPersonId;
    if (lead !== null && (typeof lead !== "string" || !personIds.has(lead))) {
      add(
        "company.json",
        `crews[${index}].leadPersonId names ${String(lead)}, who is not one of the people; use a person id, or null when a cleaner leads`,
      );
    }
    if (whole(crew.members, 1)) crewMembers += crew.members as number;
    else add("company.json", `crews[${index}] (${id}) needs a whole members of at least 1`);
    if (!whole(crew.weeklyHoursCap, 1)) {
      add("company.json", `crews[${index}] (${id}) needs a whole weeklyHoursCap of at least 1`);
    }
    const name = text(crew.name);
    if (name !== undefined && !source.handbook.includes(name)) {
      add("handbook.md", `does not name the crew ${name}; the handbook must describe every crew`);
    }
  }
  // Convention: crews' members are crew staff not listed in people; the people are counted once, here.
  // The crews count the field staff who are not listed as people; the people are counted once, here.
  const headcount = asRecord(company.profile)?.headcount;
  if (crews !== undefined && Number.isSafeInteger(headcount)) {
    const total = crewMembers + personIds.size;
    if (total !== headcount) {
      add(
        "company.json",
        `crews plus the people add up to ${total} (${crewMembers} crew members and ${personIds.size} people) but profile.headcount is ${String(headcount)}`,
      );
    }
  }

  const staff = asRecord(company.staffPolicies);
  if (staff === undefined) {
    add("company.json", "staffPolicies is missing");
  } else {
    if (!whole(staff.timeOffNoticeDays, 0)) {
      add("company.json", "staffPolicies.timeOffNoticeDays must be a whole number of days");
    }
    // A default, not a lock: the customer may set it false, but the policies must say so too.
    if (typeof staff.overtimeNeedsApproval !== "boolean") {
      add("company.json", "staffPolicies.overtimeNeedsApproval must be true or false");
    } else {
      const [stated, other] = staff.overtimeNeedsApproval
        ? [OVERTIME_NEEDS_APPROVAL, OVERTIME_NEEDS_NO_APPROVAL]
        : [OVERTIME_NEEDS_NO_APPROVAL, OVERTIME_NEEDS_APPROVAL];
      if (!source.policies.includes(stated) || source.policies.includes(other)) {
        add(
          "policies.md",
          `must say "${stated}" (and not "${other}") to agree with staffPolicies.overtimeNeedsApproval`,
        );
      }
    }
    // The People Ops role routes protected leave and workplace complaints by these; without them it
    // would fall back silently to someone the company never chose.
    for (const key of [
      "payQuestionsTo",
      "disciplineTo",
      "protectedLeaveTo",
      "employeeRelationsTo",
    ]) {
      if (!(key in staff))
        add("company.json", `staffPolicies.${key} is missing; name the person by id`);
    }
    for (const [key, value] of Object.entries(staff)) {
      if (!key.endsWith("To")) continue;
      if (typeof value !== "string" || !personIds.has(value)) {
        add(
          "company.json",
          `staffPolicies.${key} names ${String(value)}, who is not one of the people`,
        );
      }
    }
  }

  // Who approves what marketing publishes is the company's own choice; the Marketing role asks them.
  const approver = asRecord(company.marketing)?.approverId;
  if (typeof approver !== "string" || !personIds.has(approver)) {
    add(
      "company.json",
      `marketing.approverId names ${String(approver)}, who is not one of the people; name the person who approves what marketing publishes`,
    );
  }

  const claims = asArray(asRecord(company.marketing)?.approvedClaims);
  if (claims === undefined || claims.length === 0) {
    add("company.json", "marketing.approvedClaims is missing or empty");
  }
  for (const [index, claim] of (claims ?? []).entries()) {
    const statement = text(claim);
    if (statement === undefined) add("company.json", `marketing.approvedClaims[${index}] is empty`);
    else if (!source.policies.includes(statement)) {
      add(
        "policies.md",
        `does not state the approved claim "${statement}"; the policies must list every claim marketing may make`,
      );
    }
  }

  // Testimonials are optional, but one that is on record needs the words and who said them: the
  // desk quotes a customer only from here.
  const testimonials = asRecord(company.marketing)?.testimonials;
  if (testimonials !== undefined) {
    if (!Array.isArray(testimonials)) {
      add("company.json", "marketing.testimonials must be a list of { quote, attribution }");
    } else {
      const fix = {
        quote: "write the customer's words exactly as recorded",
        attribution: 'name who said it, e.g. "Name, role, Company"',
      } as const;
      for (const [index, entry] of testimonials.entries()) {
        const record = asRecord(entry);
        if (record === undefined) {
          add(
            "company.json",
            `marketing.testimonials[${index}] must be an object { "quote": "…", "attribution": "…" }`,
          );
          continue;
        }
        for (const field of ["quote", "attribution"] as const) {
          const value = record[field];
          if (value !== undefined && typeof value !== "string") {
            add(
              "company.json",
              `marketing.testimonials[${index}].${field} must be a non-empty string: ${fix[field]}`,
            );
          } else if (text(value) === undefined) {
            add(
              "company.json",
              `marketing.testimonials[${index}].${field} is empty: ${fix[field]}`,
            );
          }
        }
      }
    }
  }

  if (!whole(asRecord(company.approvalLimits)?.purchaseOrderOverCents, 1)) {
    add(
      "company.json",
      "approvalLimits.purchaseOrderOverCents must be a whole, positive number of cents",
    );
  }
}

/** Every money amount in a markdown document, as written and in cents. */
export function moneyAmounts(markdown: string): readonly { text: string; cents: number }[] {
  const found: { text: string; cents: number }[] = [];
  for (const match of markdown.matchAll(/\$\s?([\d,]+)(?:\.(\d{1,2}))?/g)) {
    const whole = Number((match[1] ?? "").replaceAll(",", ""));
    const cents = match[2] === undefined ? 0 : Number(match[2].padEnd(2, "0"));
    if (!Number.isSafeInteger(whole)) continue;
    found.push({ text: match[0], cents: whole * 100 + cents });
  }
  return found;
}

/** The handbook skill: the model-facing entry point to the company. */
export function renderSkill(source: CompanySource): string {
  const name = text(asRecord(source.company.profile)?.tradingName) ?? "the business";
  const description =
    `The company's own facts for ${name}: who works there, what a job looks like from enquiry to ` +
    "invoice, what it sells, who decides what, and the words it uses. Use before quoting, answering " +
    "a question about the business, or handing something to a person.";
  return [
    "---",
    `name: ${HANDBOOK_SKILL}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    HEADER("handbook.md"),
    "",
    source.handbook.trim(),
    "",
    "## Where the rest is",
    "",
    "Two documents sit beside this one and load only when they are needed. Ask `read_skill` for",
    `\`${HANDBOOK_SKILL}\` with the file path:`,
    "",
    "- `references/pricing.md` — every price, every minimum, and what may be quoted without a person.",
    "- `references/policies.md` — refunds, discounts, safety, data handling, and who decides what.",
    "",
    "Every price on a quote comes from that price list. A price that is not in it is not this role's",
    "to give.",
    "",
  ].join("\n");
}

/** The price list as the model reads it. */
export function renderPricing(source: CompanySource): string {
  return `${HEADER("pricing.md")}\n\n${source.pricing.trim()}\n`;
}

/** The policies as the model reads them. */
export function renderPolicies(source: CompanySource): string {
  return `${HEADER("policies.md")}\n\n${source.policies.trim()}\n`;
}

/**
 * The same facts for the role's own code, so a tool quotes the price book rather than a copy of it
 * kept in a constant. JSON rather than TypeScript: the file is data, and a role imports none of it
 * at build time — it reads it from its own package at run time, which keeps a published role's
 * `dist` independent of the repository's layout.
 */
export function renderFacts(source: CompanySource): string {
  const facts = {
    generated: {
      from: `${COMPANY_DIRECTORY}/company.json`,
      by: GENERATOR,
      note: "Do not edit this file: run `npm run sync-company` from the repository root and commit the result.",
    },
    ...source.company,
  };
  return `${JSON.stringify(facts, null, 2)}\n`;
}

/**
 * The role packages under `agents/`: a directory with an `officehum.json`. Every one of them gets
 * the company, because every role in this catalogue works for the same business.
 */
export function roleDirectories(root: string): readonly string[] {
  const agents = join(root, "agents");
  if (!existsSync(agents)) return [];
  return readdirSync(agents, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .filter((entry) => existsSync(join(agents, entry.name, "officehum.json")))
    .map((entry) => entry.name)
    .sort();
}

/** Every generated file for one role, in the order a reader meets them. */
export function roleFiles(role: string, source: CompanySource): readonly GeneratedFile[] {
  // Paths are written with `/` whatever the platform: a copy generated on Windows has to be the same
  // bytes as one generated on Linux, or the drift test fails for the wrong reason.
  const base = `agents/${role}/skills/${HANDBOOK_SKILL}`;
  return [
    { path: `${base}/SKILL.md`, content: renderSkill(source) },
    { path: `${base}/references/pricing.md`, content: renderPricing(source) },
    { path: `${base}/references/policies.md`, content: renderPolicies(source) },
    { path: `${base}/references/facts.json`, content: renderFacts(source) },
  ];
}

/**
 * The whole catalogue's generated files, in memory. Refuses a company package that disagrees with
 * itself, and a role that does not declare the skill it is about to be given — the generated folder
 * would make that role's package invalid, which is better found here than by a test that reads the
 * role.
 */
export function renderAll(root: string): readonly GeneratedFile[] {
  const source = readSource(root);
  const issues = companyIssues(source);
  if (issues.length > 0) {
    throw new Error(
      `The company package is inconsistent, so nothing was rendered:\n${issues.map((issue) => `  ${issue}`).join("\n")}`,
    );
  }
  const files: GeneratedFile[] = [];
  for (const role of roleDirectories(root)) {
    const manifest = JSON.parse(
      readFileSync(join(root, "agents", role, "officehum.json"), "utf8"),
    ) as {
      skills?: { id?: unknown }[];
    };
    const declared = (manifest.skills ?? []).some((skill) => skill.id === HANDBOOK_SKILL);
    if (!declared) {
      throw new Error(
        `agents/${role}/officehum.json does not declare the ${HANDBOOK_SKILL} skill, so the generated copies would make its package invalid: add { "id": "${HANDBOOK_SKILL}", "enabledByDefault": true } to its skills`,
      );
    }
    files.push(...roleFiles(role, source));
  }
  return files;
}

/**
 * The generated files whose copy on disk is missing or different, with the reason each one differs.
 * This is what the drift test reports, so a stale copy names itself and the command that fixes it.
 */
export function drift(root: string): readonly GeneratedFile[] {
  return renderAll(root).filter((file) => {
    const path = join(root, file.path);
    return !existsSync(path) || readFileSync(path, "utf8") !== file.content;
  });
}

/**
 * Files under a role's generated handbook folder that the generator does not write: a reference
 * added by hand there would reach the model as company fact without passing the company package's
 * checks, and syncing would never remove it. Paths use `/`, sorted.
 */
export function unexpectedFiles(root: string): readonly string[] {
  const expected = new Set(renderAll(root).map((file) => file.path));
  const found: string[] = [];
  const walk = (relative: string): void => {
    const absolute = join(root, relative);
    if (!existsSync(absolute)) return;
    for (const entry of readdirSync(absolute, { withFileTypes: true })) {
      const path = `${relative}/${entry.name}`;
      if (entry.isDirectory()) walk(path);
      else if (!expected.has(path)) found.push(path);
    }
  };
  for (const role of roleDirectories(root)) walk(`agents/${role}/skills/${HANDBOOK_SKILL}`);
  return found.sort();
}

/** Writes every generated file; returns the paths it changed and the paths already correct. */
export function syncCompany(root: string): {
  readonly written: readonly string[];
  readonly unchanged: readonly string[];
} {
  const written: string[] = [];
  const unchanged: string[] = [];
  for (const file of renderAll(root)) {
    const path = join(root, file.path);
    const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
    if (current === file.content) {
      unchanged.push(file.path);
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, file.content);
    written.push(file.path);
  }
  return { written, unchanged };
}

/** A number in a record, or zero, so an arithmetic check reports rather than throws. */
function number(record: Readonly<Record<string, unknown>>, key: string): number {
  const value = record[key];
  return typeof value === "number" ? value : 0;
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return undefined;
  return value as Record<string, unknown>;
}

function asArray(value: unknown): readonly unknown[] | undefined {
  return Array.isArray(value) ? (value as readonly unknown[]) : undefined;
}

function text(value: unknown): string | undefined {
  return typeof value === "string" && value.trim() !== "" ? value : undefined;
}

/** Every `…Cents` field of the company record, by value, with the path that records it. */
function walkCents(value: unknown, path: string, into: Map<number, string>): void {
  if (Array.isArray(value)) {
    for (const [index, item] of value.entries()) walkCents(item, `${path}[${index}]`, into);
    return;
  }
  const record = asRecord(value);
  if (record === undefined) return;
  for (const [key, child] of Object.entries(record)) {
    const at = path === "" ? key : `${path}.${key}`;
    if (key.endsWith("Cents") && typeof child === "number" && Number.isSafeInteger(child)) {
      into.set(child, at);
    }
    walkCents(child, at, into);
  }
}
